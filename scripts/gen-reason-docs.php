<?php
// Generates docs/14-REASON-CODES.md from panel/reasons.php (the registry) and panel/lang.php (the words).
//
//   php scripts/gen-reason-docs.php            write docs/14-REASON-CODES.md
//   php scripts/gen-reason-docs.php --check    exit 1 when the file on disk is not what the registry produces (CI)
//   php scripts/gen-reason-docs.php --stdout   print it
//
// Nothing here reads a log or a config: the page is a pure function of the registry, so it cannot drift from the panel.
define('GP_BOOT', 1);
$root = dirname(__DIR__);
$GP_LANG = require $root . '/panel/lang.php';
function gp_t($key) { global $GP_LANG; return isset($GP_LANG[$key]) ? $GP_LANG[$key] : $key; }
require $root . '/panel/reasons.php';

function gp_doc_cell($s) { return str_replace(array('|', "\n"), array('\\|', ' '), (string)$s); }

function gp_reason_docs() {
	$o = "<!-- Generated by scripts/gen-reason-docs.php from panel/reasons.php and panel/lang.php. Do not edit by hand: change the registry or the\n     strings and run the script (CI fails when this file is out of date). -->\n\n";
	$o .= "# Reason codes and short log fields\n\n";
	$o .= "Every log row keeps SHORT codes: they are written on every request, and the analyzer, the Logs filters, saved links and old logs depend on\n";
	$o .= "them, so they are never renamed. The admin panel shows the full name next to the code everywhere a reason appears (Logs, Identity, the\n";
	$o .= "dashboard lists), with the explanation as a tooltip. This page is the same list. The Reason filter on the Logs page offers the full\n";
	$o .= "names; its value is still the code.\n\n";
	$o .= "## Monitor only: the `SH_` prefix\n\n";
	$o .= "A code that starts with `SH_` (for example `SH_RULE:<id>`, `SH_IPL_BLOCK:<id>`, `SH_403`) is the monitor-only (shadow) form: the guard would have acted, and did nothing. The panel draws a \"" . gp_t('rsn_monitor_word') . "\" marker on the badge.\n\n";
	$o .= "## Codes with an id\n\n";
	$o .= "`RULE:<id>` names an access rule, `IPL_BLOCK:<id>` and `IPL_ALLOW:<id>` name an IP list. The panel resolves the id to the rule or list name and links to it; an id that no longer exists is struck through.\n\n";
	$o .= "## Reason codes\n\n";
	$o .= "| Code | Full name | Category | What it means |\n|---|---|---|---|\n";
	$reg = gp_reason_registry();
	$cats = array_keys(gp_reason_categories());
	uksort($reg, function ($a, $b) use ($reg, $cats) {
		$a = (string)$a; $b = (string)$b;
		$c = array_search($reg[$a], $cats, true) - array_search($reg[$b], $cats, true);
		return $c !== 0 ? $c : strcmp($a, $b);
	});
	foreach ($reg as $base => $cat) {
		$base = (string)$base;
		$code = gp_reason_has_id($base) ? $base . ':<id>' : (gp_reason_is_action($base) ? 'SH_' . $base : $base);
		$o .= '| `' . $code . '` | ' . gp_doc_cell(gp_t('rsn_' . $base)) . ' | ' . gp_doc_cell(gp_t('rsn_cat_' . $cat)) . ' | ' . gp_doc_cell(gp_t('rsn_' . $base . '_x')) . " |\n";
	}
	$o .= "\n`SH_CAPT_ESC` is the monitor-only form of `CAPT_ESC` (the proof of work looked headless, but CAPTCHA escalation is not enforced).\n\n";
	$o .= "## Categories\n\n";
	foreach (array_keys(gp_reason_categories()) as $c) { $o .= '* ' . gp_t('rsn_cat_' . $c) . "\n"; }
	$o .= "\n## Other short fields of a log row\n\n";
	$o .= "| Field | Full name | Values |\n|---|---|---|\n";
	foreach (gp_field_registry() as $field => $def) {
		$vals = array();
		foreach ($def[1] as $v => $k) { $vals[] = '`' . ($v === '' ? '(empty)' : $v) . '` ' . gp_t($k); }
		$o .= '| `' . $field . '` | ' . gp_doc_cell(gp_t($def[0])) . ' | ' . gp_doc_cell(implode('; ', $vals)) . " |\n";
	}
	return $o;
}

$text = gp_reason_docs();
$file = $root . '/docs/14-REASON-CODES.md';
$mode = isset($argv[1]) ? $argv[1] : '';
if ($mode === '--stdout') { echo $text; exit(0); }
if ($mode === '--check') {
	$have = is_file($file) ? file_get_contents($file) : '';
	if ($have !== $text) { fwrite(STDERR, "docs/14-REASON-CODES.md is out of date: run php scripts/gen-reason-docs.php\n"); exit(1); }
	echo "docs/14-REASON-CODES.md is up to date\n";
	exit(0);
}
file_put_contents($file, $text);
echo "wrote docs/14-REASON-CODES.md\n";
